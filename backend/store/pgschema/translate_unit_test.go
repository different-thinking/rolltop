// TestTranslateStripsWithoutRowid covers the SQLite storage-form suffix, and
// pins that any other trailing clause is refused instead of dropped.
func TestTranslateStripsWithoutRowid(t *testing.T) {
	objects := translateOne(t, TableKind, "t", `CREATE TABLE t (a INTEGER NOT NULL, PRIMARY KEY (a)) WITHOUT ROWID`)
	if strings.Contains(strings.ToUpper(objects[0].SQL), "WITHOUT ROWID") {
		t.Errorf("WITHOUT ROWID survived:\n%s", objects[0].SQL)
	}
	if _, err := Translate([]SQLiteObject{{Kind: TableKind, Name: "t", SQL: `CREATE TABLE t (a INTEGER) STRICT`}}); err == nil {
		t.Error("an unknown trailing clause was accepted")
	}
}

// TestTranslateRejectsUntranslatedSQLiteExpressions keeps CHECK constraints
// from silently losing their meaning: a dropped constraint is one the
// database stops enforcing.
func TestTranslateRejectsUntranslatedSQLiteExpressions(t *testing.T) {
	if _, err := Translate([]SQLiteObject{{Kind: TableKind, Name: "t", SQL: `CREATE TABLE t (
		a TEXT NOT NULL CHECK (a NOT GLOB '*[^0-9]*')
	)`}}); err == nil {
		t.Error("an untranslated GLOB was accepted")
	}
	if _, err := Translate([]SQLiteObject{{Kind: IndexKind, Name: "i", SQL: `CREATE INDEX i ON t(a) WHERE a > strftime('%s', 'now')`}}); err == nil {
		t.Error("an untranslated strftime was accepted")
	}
}

