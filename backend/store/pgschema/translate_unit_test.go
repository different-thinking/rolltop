// TestTranslateTriggerPinsItsSource is the drift guard: matching on the name
// alone would keep emitting a stale translation after the SQLite body
// changed, leaving the golden file byte-identical.
func TestTranslateTriggerPinsItsSource(t *testing.T) {
	changed := strings.Replace(duplicatePointerTriggerSQLite, "= 0", "= -1", 1)
	if _, err := Translate([]SQLiteObject{{Kind: TriggerKind, Name: "messages_clear_duplicate_pointer", SQL: changed}}); err == nil {
		t.Error("a changed trigger body was accepted with the old translation")
	}
	if _, err := Translate([]SQLiteObject{{Kind: TriggerKind, Name: "messages_clear_duplicate_pointer", SQL: duplicatePointerTriggerSQLite}}); err != nil {
		t.Errorf("the pinned trigger body was rejected: %v", err)
	}
}

// TestTranslateSortsByName keeps the golden file independent of SQLite's
// physical page layout, which shifts when a migration rebuilds a table.
func TestTranslateSortsByName(t *testing.T) {
	objects, err := Translate([]SQLiteObject{
		{Kind: TableKind, Name: "zebra", SQL: `CREATE TABLE zebra (a INTEGER)`},
		{Kind: TableKind, Name: "alpha", SQL: `CREATE TABLE alpha (a INTEGER)`},
	})
	if err != nil {
		t.Fatal(err)
	}
	if objects[0].Name != "alpha" || objects[1].Name != "zebra" {
		t.Errorf("tables not name-sorted: %s, %s", objects[0].Name, objects[1].Name)
	}
}

