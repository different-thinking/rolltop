-- The shopping list becomes one list on which the same thing to buy stands
-- once, its amounts added up across recipes ("400 g Tomaten" from two recipes
-- is "800 g Tomaten"). An item now carries what it adds up to -- amount, the
-- unit it is counted in, the name to buy, and the key that decides which
-- lines add up -- and where it came from moves into a table of its own,
-- because one item can now come from several recipes.
--
-- Reading an ingredient line as amount, unit and name is Go code
-- (recipe.ParseIngredient), so this migration only makes the room for it.
-- Every item that exists already is left with an empty merge_key, and the
-- plugin folds those into the new shape the next time it touches the
-- reader's list (foldLegacyShopping): it records each one's recipe, section
-- and text as its source, then merges the items that add up, open with open
-- and bought with bought. The old columns recipe_id, recipe_title and section
-- stay so that an older build can still read the table, and nothing writes them
-- any more.
ALTER TABLE plugin_recipe_box_shopping_items ADD COLUMN IF NOT EXISTS amount DOUBLE PRECISION NOT NULL DEFAULT 0;
ALTER TABLE plugin_recipe_box_shopping_items ADD COLUMN IF NOT EXISTS has_amount INTEGER NOT NULL DEFAULT 0;
ALTER TABLE plugin_recipe_box_shopping_items ADD COLUMN IF NOT EXISTS unit TEXT NOT NULL DEFAULT '';
ALTER TABLE plugin_recipe_box_shopping_items ADD COLUMN IF NOT EXISTS name TEXT NOT NULL DEFAULT '';
ALTER TABLE plugin_recipe_box_shopping_items ADD COLUMN IF NOT EXISTS merge_key TEXT NOT NULL DEFAULT '';

CREATE INDEX IF NOT EXISTS idx_plugin_recipe_box_shopping_items_key ON plugin_recipe_box_shopping_items(user_id, merge_key, checked_at);

CREATE TABLE IF NOT EXISTS plugin_recipe_box_shopping_sources (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  item_id BIGINT NOT NULL REFERENCES plugin_recipe_box_shopping_items(id) ON DELETE CASCADE,
  recipe_id BIGINT NOT NULL DEFAULT 0,
  recipe_title TEXT NOT NULL DEFAULT '',
  section TEXT NOT NULL DEFAULT '',
  text TEXT NOT NULL,
  created_at BIGINT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_plugin_recipe_box_shopping_sources_item ON plugin_recipe_box_shopping_sources(user_id, item_id);
CREATE INDEX IF NOT EXISTS idx_plugin_recipe_box_shopping_sources_recipe ON plugin_recipe_box_shopping_sources(user_id, recipe_id);
