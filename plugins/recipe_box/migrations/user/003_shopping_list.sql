-- The shopping list: what the reader means to buy, gathered from the
-- ingredients of one recipe after another and from what they type in
-- themselves. An item from a recipe keeps the recipe's id and a copy of its
-- name and section, so the list still says where an item came from after the
-- recipe was taken out of the cookbook. An item of the reader's own carries
-- recipe_id 0. Ticking an item off keeps it on the list, checked, until the
-- reader clears what they bought.
CREATE TABLE IF NOT EXISTS plugin_recipe_box_shopping_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  recipe_id BIGINT NOT NULL DEFAULT 0,
  recipe_title TEXT NOT NULL DEFAULT '',
  section TEXT NOT NULL DEFAULT '',
  text TEXT NOT NULL,
  checked_at BIGINT NOT NULL DEFAULT 0,
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_plugin_recipe_box_shopping_items_user ON plugin_recipe_box_shopping_items(user_id, recipe_id, id);
