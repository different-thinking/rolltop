-- The recipe box keeps four things per reader. Settings say whether it runs at
-- all, which mail it may read and where it files what it found, and hold the
-- scan cursor that is the backfill. A link is one page some note-to-self named,
-- and the answer the page gave. A recipe is what a page that published one
-- said, kept so it survives the page. And a mail is one note-to-self with the
-- links it carried and what the box did with it.
--
-- Nothing is decided for a reader who has not switched it on: the absence of a
-- settings row means off, so enabling the plugin for an installation moves
-- nobody's mail.
CREATE TABLE IF NOT EXISTS plugin_recipe_box_settings (
  user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  enabled INTEGER NOT NULL DEFAULT 0,
  own_recipients_only INTEGER NOT NULL DEFAULT 1,
  move_enabled INTEGER NOT NULL DEFAULT 1,
  folder_name TEXT NOT NULL DEFAULT 'Recipes',
  scan_cursor BIGINT NOT NULL DEFAULT 0,
  scan_started_at BIGINT NOT NULL DEFAULT 0,
  scan_finished_at BIGINT NOT NULL DEFAULT 0,
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS plugin_recipe_box_recipes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  canonical_url TEXT NOT NULL,
  title TEXT NOT NULL DEFAULT '',
  description TEXT NOT NULL DEFAULT '',
  site_name TEXT NOT NULL DEFAULT '',
  author TEXT NOT NULL DEFAULT '',
  yield TEXT NOT NULL DEFAULT '',
  total_minutes INTEGER NOT NULL DEFAULT 0,
  prep_minutes INTEGER NOT NULL DEFAULT 0,
  cook_minutes INTEGER NOT NULL DEFAULT 0,
  calories TEXT NOT NULL DEFAULT '',
  rating_value DOUBLE PRECISION NOT NULL DEFAULT 0,
  rating_count INTEGER NOT NULL DEFAULT 0,
  ingredients_json TEXT NOT NULL DEFAULT '[]',
  instructions_json TEXT NOT NULL DEFAULT '[]',
  categories_json TEXT NOT NULL DEFAULT '[]',
  cuisines_json TEXT NOT NULL DEFAULT '[]',
  keywords_json TEXT NOT NULL DEFAULT '[]',
  image_urls_json TEXT NOT NULL DEFAULT '[]',
  image_data BYTEA,
  image_type TEXT NOT NULL DEFAULT '',
  image_status TEXT NOT NULL DEFAULT '',
  origin TEXT NOT NULL DEFAULT 'structured',
  dismissed INTEGER NOT NULL DEFAULT 0,
  search_text TEXT NOT NULL DEFAULT '',
  first_seen_at BIGINT NOT NULL DEFAULT 0,
  fetched_at BIGINT NOT NULL DEFAULT 0,
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL,
  UNIQUE(user_id, canonical_url)
);

CREATE INDEX IF NOT EXISTS idx_plugin_recipe_box_recipes_user_seen ON plugin_recipe_box_recipes(user_id, dismissed, first_seen_at DESC, id DESC);

CREATE TABLE IF NOT EXISTS plugin_recipe_box_links (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  url TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending',
  forced INTEGER NOT NULL DEFAULT 0,
  attempts INTEGER NOT NULL DEFAULT 0,
  next_attempt_at BIGINT NOT NULL DEFAULT 0,
  error TEXT NOT NULL DEFAULT '',
  recipe_id BIGINT NOT NULL DEFAULT 0,
  final_url TEXT NOT NULL DEFAULT '',
  title TEXT NOT NULL DEFAULT '',
  description TEXT NOT NULL DEFAULT '',
  image_url TEXT NOT NULL DEFAULT '',
  site_name TEXT NOT NULL DEFAULT '',
  fetched_at BIGINT NOT NULL DEFAULT 0,
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL,
  UNIQUE(user_id, url)
);

CREATE INDEX IF NOT EXISTS idx_plugin_recipe_box_links_due ON plugin_recipe_box_links(user_id, status, next_attempt_at);
CREATE INDEX IF NOT EXISTS idx_plugin_recipe_box_links_recipe ON plugin_recipe_box_links(user_id, recipe_id);

CREATE TABLE IF NOT EXISTS plugin_recipe_box_mails (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  message_key TEXT NOT NULL,
  message_id BIGINT NOT NULL DEFAULT 0,
  message_id_header TEXT NOT NULL DEFAULT '',
  account_id BIGINT NOT NULL DEFAULT 0,
  subject TEXT NOT NULL DEFAULT '',
  date_unix BIGINT NOT NULL DEFAULT 0,
  note TEXT NOT NULL DEFAULT '',
  move_state TEXT NOT NULL DEFAULT '',
  move_attempts INTEGER NOT NULL DEFAULT 0,
  move_next_at BIGINT NOT NULL DEFAULT 0,
  move_error TEXT NOT NULL DEFAULT '',
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL,
  UNIQUE(user_id, message_key)
);

CREATE INDEX IF NOT EXISTS idx_plugin_recipe_box_mails_move ON plugin_recipe_box_mails(user_id, move_state);

CREATE TABLE IF NOT EXISTS plugin_recipe_box_mail_links (
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  mail_id BIGINT NOT NULL REFERENCES plugin_recipe_box_mails(id) ON DELETE CASCADE,
  link_id BIGINT NOT NULL REFERENCES plugin_recipe_box_links(id) ON DELETE CASCADE,
  position INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY(mail_id, link_id)
);

CREATE INDEX IF NOT EXISTS idx_plugin_recipe_box_mail_links_link ON plugin_recipe_box_mail_links(user_id, link_id);
